from __future__ import annotations

import os
from time import perf_counter

import pytest

from tests.datasets import load_compatible_templates
from vesma import cmol_from_smiles
from vesma.cpu_matcher import CpuReactionMatcher
from vesma.prefilter import (
    SparseRuleFingerprintIndex,
    cpu_sparse_path_feature_provider,
)

pytestmark = [pytest.mark.perf]


def env_int(name: str) -> int | None:
    value = os.environ.get(name)
    return None if value is None else int(value)


def test_perf_path_prefilter_prunes_small_n1_frontier(
    small_paroutes_corpus,
    small_paroutes_templates,
) -> None:
    """Print raw sparse path prune metrics for n1-subset frontier x USPTO rules.

    This benchmark does not write result files. Use ``PREFILTER_RULE_LIMIT`` for
    smoke runs and ``PREFILTER_FRONTIER=layer1`` to benchmark the next frontier
    generated by the small reference-template control.
    """

    rule_limit = env_int("PREFILTER_RULE_LIMIT")
    frontier_mode = os.environ.get("PREFILTER_FRONTIER", "targets")

    load_started = perf_counter()
    uspto = load_compatible_templates()[:rule_limit]
    rules = tuple(template.pattern for template in uspto)
    load_seconds = perf_counter() - load_started

    products = [
        cmol_from_smiles(smiles)[0] for smiles in small_paroutes_corpus.target_smiles
    ]
    if frontier_mode == "layer1":
        control = CpuReactionMatcher(
            tuple(template.pattern for template in small_paroutes_templates)
        )
        layer1, _ = control.match(products)
        products = list(layer1)
    elif frontier_mode != "targets":
        raise ValueError("PREFILTER_FRONTIER must be 'targets' or 'layer1'.")

    index_started = perf_counter()
    index = SparseRuleFingerprintIndex.from_rules(rules)
    index_seconds = perf_counter() - index_started

    feature_started = perf_counter()
    molecule_features = cpu_sparse_path_feature_provider(products)
    feature_seconds = perf_counter() - feature_started
    atom_counts = [product.atom_count for product in products]

    pair_started = perf_counter()
    candidates = index.candidate_pairs(molecule_features, atom_counts)
    pair_seconds = perf_counter() - pair_started

    dense_pairs = len(products) * len(rules)
    pruned = dense_pairs - len(candidates)
    print(
        {
            "frontier_mode": frontier_mode,
            "frontier_count": len(products),
            "rule_count": len(rules),
            "dense_pairs": dense_pairs,
            "candidate_pairs": len(candidates),
            "pruned_pairs": pruned,
            "prune_ratio": 0.0 if dense_pairs == 0 else pruned / dense_pairs,
            "load_seconds": load_seconds,
            "index_seconds": index_seconds,
            "feature_seconds": feature_seconds,
            "pair_seconds": pair_seconds,
        }
    )
